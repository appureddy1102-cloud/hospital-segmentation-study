md("""
## 6. Statistical analysis and outlier treatment

Skewness and kurtosis are measured on the raw features, then log1p is applied where justified and the
effect is quantified. IQR and Z-score outlier counts are reported — **not** to delete those patients,
but to prove the segmentation must be robust to them.
""")
code("""
from scipy import stats
cols = ["recency_days","frequency","monetary","avg_billing_per_visit","total_bed_days","lab_count"]
rows = []
for c in cols:
    x = feat[c].astype(float)
    xl = np.log1p(x.clip(lower=0))
    rows.append({"feature": c,
                 "skew_raw": round(float(stats.skew(x)), 3),
                 "kurtosis_raw": round(float(stats.kurtosis(x)), 3),
                 "skew_log1p": round(float(stats.skew(xl)), 3),
                 "kurtosis_log1p": round(float(stats.kurtosis(xl)), 3),
                 "zscore_outliers_3sd": int((np.abs(stats.zscore(x)) > 3).sum()),
                 "iqr_outliers": int((x > x.quantile(.75) + 1.5*(x.quantile(.75)-x.quantile(.25))).sum())})
pd.DataFrame(rows)
""")
